MANAGERS = {"owner", "tenant-admin"}
STAFF = {"owner", "tenant-admin", "manager", "reception", "professional"}


def applies_to(user):
    """Only people who work inside a company sign it; patients and the platform team do not."""
    return bool(user and user.is_authenticated and getattr(user, "tenant_id", None) and user.role in STAFF
                and not user.is_superuser)


def _person(user):
    return user.get_full_name() or user.email


def _registration(user):
    from scheduling.models import Professional
    professional = Professional.objects.filter(tenant_id=user.tenant_id, user=user, active=True).first()
    if professional is None:
        return None
    reg = getattr(professional, "clinical_registration", None)
    return f"{reg.council} {reg.jurisdiction}/{reg.number}" if reg else "CRO não cadastrado"


def blocks_for(user, document):
    """Declarations shown to this person, by profile (section 8). Each block: role, intro and the boxes to tick."""
    version = document.version
    blocks = []
    if user.role in MANAGERS:
        tenant = user.tenant
        blocks.append({"role": "empresa", "title": "Aceite da empresa (representante legal)",
            "intro": (f"Declaro que represento legalmente a empresa {tenant.name}, CNPJ/CPF {tenant.document or 'não informado'}, "
                      f"e que li e aceito a {TITLE}, versão {version}."),
            "items": ["A Clínica é a Controladora dos dados de seus Pacientes e responde pela base legal de cada tratamento.",
                      "A Clínica só registrará consentimentos que os Pacientes realmente deram e guardará a prova.",
                      "A Clínica responde pelos atos de seus Usuários e removerá o acesso de quem sair da equipe.",
                      "A Clínica confere seu caixa e cuida de suas obrigações fiscais e contábeis."]})
    registration = _registration(user) if user.role in STAFF else None
    if registration is not None or user.role == "professional":
        blocks.append({"role": "profissional", "title": "Aceite do profissional de odontologia",
            "intro": f"Eu, {_person(user)}, {registration or 'CRO não cadastrado'}, li e aceito a {TITLE}, versão {version}.",
            "items": ["Sou responsável pelo que registro no prontuário e pelos documentos clínicos que emito e assino.",
                      "Manterei sigilo profissional sobre os dados que acessar.",
                      "Meu login é pessoal e não será compartilhado."]})
    elif user.role not in MANAGERS:
        blocks.append({"role": "usuario", "title": "Aceite do usuário (recepção e gestão)",
            "intro": f"Eu, {_person(user)}, li e aceito a {TITLE}, versão {version}.",
            "items": ["Usarei os dados de Pacientes só para o trabalho na Clínica e manterei sigilo.",
                      "Meu login é pessoal e não será compartilhado.",
                      "Lançamentos e correções que eu fizer ficam registrados em meu nome."]})
    return blocks
